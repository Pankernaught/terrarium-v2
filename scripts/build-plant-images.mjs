#!/usr/bin/env node
/**
 * Generates src/data/plant-images.ts — a static Metro asset registry mapping
 * plant slugs to require() calls for their photos (PNG or JPG).
 *
 * Metro cannot bundle dynamic require() strings, so this codegen step is
 * necessary. Run after adding a photo to assets/plants/:
 *   node scripts/build-plant-images.mjs
 *
 * Plant-admin runs it automatically on every photo save.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('..', import.meta.url);
const ASSETS_DIR = fileURLToPath(new URL('assets/plants', ROOT));
const OUT_FILE = fileURLToPath(new URL('src/data/plant-images.ts', ROOT));

const images = readdirSync(ASSETS_DIR)
  .filter((f) => f.endsWith('.png') || f.endsWith('.jpg'))
  .sort();

const entries = images
  .map((f) => `  '${f.slice(0, -4)}': require('@/assets/plants/${f}'),`)
  .join('\n');

const out = [
  '// AUTO-GENERATED by scripts/build-plant-images.mjs — do not edit manually.',
  'export const PLANT_IMAGES: Partial<Record<string, number>> = {',
  entries,
  '};',
  '',
].join('\n');

writeFileSync(OUT_FILE, out, 'utf8');
console.log(`plant-images: ${images.length} photo${images.length !== 1 ? 's' : ''} → src/data/plant-images.ts`);
